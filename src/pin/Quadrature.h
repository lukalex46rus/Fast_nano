#if F_USE_QUAD

namespace fn {

class QuadDecoder {
public:
    QuadDecoder() = default;
    ~QuadDecoder() { end(); }

    QuadDecoder(const QuadDecoder&) = delete;
    QuadDecoder& operator=(const QuadDecoder&) = delete;

    Result begin(uint8_t pinA, uint8_t pinB, bool useInterrupts = true);
    Result begin(Pin a, Pin b, bool useInterrupts = true);
    void end();

    bool active() const { return (_flags & FlagActive) != 0; }
    bool useInterrupts() const { return (_flags & FlagIsr) != 0; }

    // Только для polling-режима; в режиме прерываний ничего не делает.
    void update();

    int32_t position() const;
    int32_t takeDelta();
    void reset(int32_t pos = 0);

    uint16_t errors() const;
    void clearErrors();

    Pin pinA() const { return _a; }
    Pin pinB() const { return _b; }

    // Служебное: вызывается диспетчером PCINT. Не для прикладного кода.
    void onChange(Pin changed);

private:
    static void isr(void* ctx, Pin changed);

    uint8_t readState() const;
    void apply(uint8_t s);

    static constexpr uint8_t FlagActive = 0x01;
    static constexpr uint8_t FlagIsr    = 0x02;

    Pin _a{};
    Pin _b{};
    volatile int32_t _pos = 0;
    int32_t _readPos = 0;
    volatile uint8_t _last = 0;
    volatile uint16_t _err = 0;
    uint8_t _flags = 0;
};

static_assert(sizeof(QuadDecoder) == 14,
              "fn::QuadDecoder: ожидалось 14 байт (выравнивание на AVR = 1)");

}  // namespace fn

#endif  // F_USE_QUAD