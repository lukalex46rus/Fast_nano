#pragma once
// ============================================================================
//  Quadrature.h — квадратурный декодер A/B: прерывания или опрос
//  Цель: ATmega328P/328, gnu++11
// ----------------------------------------------------------------------------
//  НАЗНАЧЕНИЕ
//    Декодирование инкрементального энкодера по двум каналам с разрешением x4:
//    каждый фронт обоих каналов даёт ±1, то есть 4 отсчёта на полный период
//    квадратуры. Работает либо от общего диспетчера fn::irq::PinChange,
//    либо в режиме опроса update(). Eigene ISR нет.
//
//  УСТРОЙСТВО ДЕКОДЕРА
//    Состояние = A | (B << 1). По разности с предыдущим состоянием:
//      diff == 0  — изменения нет;
//      diff == 3  — изменились оба канала: пропуск фронта, позиция НЕ меняется,
//                   растёт errors();
//      иначе      — направление = ((prev >> 1) ^ cur) & 1, то есть pB ^ cA.
//    Таблицы переходов нет: формула покрывает все 8 допустимых переходов и
//    стоит ~10 инструкций против LPM + 16 байт flash у табличного варианта.
//
//  API
//    class QuadDecoder                     объект, 14 байт
//      QuadDecoder() / ~QuadDecoder()      деструктор снимает регистрацию
//      begin(pinA, pinB, useInterrupts = true) -> Result
//      begin(Pin a, Pin b, useInterrupts = true) -> Result
//      end()
//      active() / useInterrupts() -> bool
//      update()                            только polling-режим
//      position() -> int32_t               атомарно
//      takeDelta() -> int32_t              приращение с прошлого вызова, атомарно
//      reset(pos = 0)                      позиция и errors() в ноль
//      errors() -> uint16_t                число недопустимых переходов
//      clearErrors()
//      pinA() / pinB() -> fn::Pin
//      onChange(Pin changed)               служебное: вызывается диспетчером
//
//    Копирование запрещено: объект зарегистрирован в диспетчере по адресу.
//
//  КОДЫ ВОЗВРАТА begin
//    Ok        запущен
//    BadArg    невалидный вывод (вне 0..19, PC7) или pinA == pinB
//    NoBuffer  в пуле диспетчера меньше двух свободных слотов
//    Busy      один из выводов уже занят другим коллбэком PCINT
//    NotReady  запрошен режим прерываний при F_USE_IRQ = 0
//
//  ОГРАНИЧЕНИЯ / ВАЖНО
//    - Размер объекта 14 байт. Указатели на регистры не кэшируются: адрес
//      вычисляется из fn::Pin арифметикой (core/Registers.h). Реестра
//      декодеров нет: контекст передаёт диспетчер.
//    - Лимит числа декодеров задаётся FN_IRQ_SLOTS (пул диспетчера), а не
//      отдельным FN_QUAD_MAX. Каждый декодер в режиме прерываний занимает
//      ДВА слота по 5 байт. При FN_IRQ_SLOTS = 8 это до 4 декодеров, если
//      PCINT больше никто не использует. Polling-режим слотов не занимает.
//    - Порядок инициализации: сначала полностью заполняется объект и
//      выставляется флаг активности, только потом attach. Прежняя версия
//      добавляла объект в реестр до инициализации — ISR мог увидеть
//      полусобранный декодер. При отказе второго attach первый снимается.
//    - Коллбэк вызывается ИЗ ISR: обновление позиции короткое, без блокировок.
//      Чтение позиции из основного кода — position() или takeDelta(), оба
//      атомарны (32-битное чтение на AVR рвётся прерыванием).
//    - Один вывод не может быть занят двумя декодерами: attach вернёт Busy.
//      Нужен веер на одном пине — делайте его внутри своего коллбэка.
//    - errors() растёт при недопустимых переходах (оба канала изменились
//      между выборками). Причины: слишком быстрое вращение (ISR не успевает),
//      дребезг механического энкодера, наводки на длинной линии.
//      Позиция при этом не меняется — лучше потерять отсчёт, чем уехать.
//    - Механический энкодер без RC-фильтра даёт дребезг: errors() будет расти,
//      позиция — шуметь. Фильтр 10 кОм + 100 нФ на каждый канал обязателен.
//      Программный дебаунс для квадратуры не применяется: он съедает фронты.
//    - Энкодер с фиксаторами обычно даёт 4 отсчёта на щелчок: делите
//      position() на 4 (сдвиг) в прикладном коде.
//    - Входы настраиваются с подтяжкой (открытый коллектор / кнопки).
//      Для push-pull выходов с внешними подтяжками снимите её после begin:
//      regs::modeInput(pinA()).
//    - Деструктор снимает только свою регистрацию в диспетчере, чужие
//      ресурсы не трогает — это не нарушает R17 (запрет глобальных побочных
//      эффектов из деструктора), а освобождает ровно то, что захвачено.
//    - logic/Encoder должен строиться поверх этого класса, а не заводиться
//      второй реализацией декодера.
//
//  СТОИМОСТЬ (AVR)
//    SRAM: 14 байт на объект + 2 слота диспетчера (10 байт) в режиме
//          прерываний. Реестра нет.
//    Flash: ~250 байт при полном использовании, таблицы нет.
//    Обработка одного фронта: ~30 тактов включая вызов из диспетчера.
//
//  ПРИМЕР
//    fn::QuadDecoder enc;
//
//    void setup() {
//        enc.begin(2, 3);                    // D2/D3, прерывания
//    }
//    void loop() {
//        int32_t d = enc.takeDelta();        // приращение с прошлого опроса
//        if (enc.errors()) { /* шум или пропуск фронтов */ enc.clearErrors(); }
//    }
//
//    // Опрос без прерываний (например, в задаче на 1 кГц):
//    enc.begin(4, 5, false);
//    enc.update();                           // вызывать чаще, чем меняется A/B
//
//  ЗАВИСИМОСТИ: core/Config.h, core/Types.h, core/Registers.h, core/Atomic.h,
//               pin/Board.h, pin/Irq.h; реализация — Quadrature.cpp
// ============================================================================

